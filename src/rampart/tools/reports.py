"""Reports: `generate_report` assembles a Conversation's Findings, vulnerability lookups, test
results and Citations into a stored Markdown Report; the Reports routes list and serve them.

Everything in a Report comes from stored records (Tool results, Citations, the Project Profile,
the answers as displayed), not from a fresh Model call, so a Report shows what actually happened.
"""

from __future__ import annotations

from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from rampart.db import to_iso, utcnow
from rampart.errors import NotFound
from rampart.models import Conversation, Message, Report, ToolCallRecord, User
from rampart.profile.service import ProfileService, profile_block

SECTIONS = ("summary", "findings", "vulnerabilities", "tests", "sources", "conversation")
MAX_ANSWER_CHARS = 6000
MAX_REPORT_CHARS = 200_000


def _cell(text: Any) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def build_report(
    db: Session, user_id: int, conversation_id: str, sections: list[str]
) -> tuple[str, str]:
    conversation = db.get(Conversation, conversation_id)
    if conversation is None or conversation.user_id != user_id:
        raise NotFound("conversation not found")
    user = db.get(User, user_id)
    messages = list(
        db.scalars(
            select(Message)
            .where(Message.conversation_id == conversation_id)
            .order_by(Message.created_at, Message.role.desc())
        )
    )
    records = list(
        db.scalars(
            select(ToolCallRecord)
            .where(
                ToolCallRecord.conversation_id == conversation_id,
                ToolCallRecord.decision == "allow",
                ToolCallRecord.result.is_not(None),
            )
            .order_by(ToolCallRecord.started_at)
        )
    )
    title = f"Security review: {conversation.title}"[:300]
    now = utcnow()
    out: list[str] = [f"# {title}", ""]
    out.append(
        f"Generated by Rampart on {to_iso(now)} for {user.username if user else 'unknown'}. "
        "Findings come from deterministic rules and recorded Tool results; answers are quoted "
        "as they were shown."
    )
    out.append("")
    out.append(
        "**Scope.** This Report covers only what was checked in this conversation: rule-based "
        "prompt and schema findings, OSV.dev lookups of the packages named, and the fixed "
        "injection suite against a local Target. It is review support, not an assessment: a "
        "missing finding does not mean the application is secure."
    )
    out.append("")

    findings = [
        (r, f)
        for r in records
        if r.tool == "analyze_prompt"
        for f in (r.result or {}).get("findings", [])
    ]
    lookups = [r for r in records if r.tool == "lookup_vulnerabilities"]
    checks = [r for r in records if r.tool == "check_dependencies"]
    tests = [r for r in records if r.tool == "run_injection_test"]
    cited: dict[str, dict[str, Any]] = {}
    for message in messages:
        for citation in message.citations or []:
            cited.setdefault(str(citation.get("passage_id")), citation)

    if "summary" in sections:
        profile = profile_block(ProfileService(db).get(user_id))
        out += ["## Summary", ""]
        out.append(f"- Questions asked: {sum(1 for m in messages if m.role == 'user')}")
        out.append(f"- Prompt and tool-schema findings: {len(findings)}")
        out.append(f"- Vulnerability lookups: {len(lookups)}")
        out.append(f"- Dependency checks: {len(checks)}")
        out.append(f"- Injection test runs: {len(tests)}")
        out.append(f"- Sources cited: {len(cited)}")
        if profile:
            out += ["", "Project Profile at the time of the report:", "", "```", profile, "```"]
        out.append("")

    if "findings" in sections:
        out += ["## Findings from prompt and tool-schema analysis", ""]
        if findings:
            out.append("| Severity | Rule | Finding | Evidence | Recommendation | References |")
            out.append("|---|---|---|---|---|---|")
            for _record, f in findings:
                out.append(
                    f"| {_cell(f.get('severity'))} | {_cell(f.get('rule'))} "
                    f"| {_cell(f.get('title'))} "
                    f"| {_cell(f.get('evidence'))} | {_cell(f.get('recommendation'))} "
                    f"| {_cell(', '.join(f.get('references') or []))} |"
                )
        else:
            out.append("No prompt or tool schema was analysed in this conversation.")
        out.append("")

    if "vulnerabilities" in sections:
        out += ["## Known vulnerabilities (OSV.dev)", ""]
        if not lookups and not checks:
            out.append("No package was looked up in this conversation.")
        for record in checks:
            result = record.result or {}
            scope = result.get("ecosystem") or "all ecosystems"
            out.append(f"### Dependency check of the Project Profile ({scope})")
            out.append("")
            out.append(
                f"{result.get('checked', 0)} of {result.get('packages', 0)} packages checked; "
                f"{result.get('vulnerabilities', 0)} known vulnerabilities in "
                f"{result.get('vulnerable_packages', 0)} packages."
            )
            if result.get("not_checked"):
                out.append(
                    f"Not checked because no exact version is known: {result['not_checked']} "
                    f"({_cell(', '.join(result.get('not_checked_names') or []))})."
                )
            rows = result.get("rows") or []
            if rows:
                out += ["", "| Package | Version | ID | Severity | Summary | Fixed in |"]
                out.append("|---|---|---|---|---|---|")
                for row in rows:
                    names = _cell(row.get("id"))
                    if row.get("aliases"):
                        names += f" ({_cell(', '.join(row['aliases']))})"
                    out.append(
                        f"| {_cell(row.get('ecosystem'))} {_cell(row.get('package'))} "
                        f"| {_cell(row.get('version'))} | {names} "
                        f"| {_cell(row.get('severity') or 'unrated')} "
                        f"| {_cell(row.get('summary'))} "
                        f"| {_cell(', '.join(row.get('fixed') or []))} |"
                    )
            if result.get("more_rows"):
                out.append(f"\n{result['more_rows']} further rows were not kept.")
            out.append("")
        for record in lookups:
            result = record.result or {}
            version = result.get("version") or "(any version)"
            label = f"{result.get('ecosystem')} {result.get('package')} {version}"
            vulns = result.get("vulnerabilities") or []
            out.append(f"### {label}")
            out.append("")
            if not vulns:
                out.append("No known vulnerabilities reported by OSV.dev.")
            else:
                out.append("| ID | Severity | Summary | Fixed in |")
                out.append("|---|---|---|---|")
                for vuln in vulns:
                    fixed = ", ".join(vuln.get("fixed_versions") or [])
                    names = _cell(vuln.get("id"))
                    if vuln.get("aliases"):
                        names += f" ({_cell(', '.join(vuln['aliases']))})"
                    out.append(
                        f"| {names} | {_cell(vuln.get('severity'))} "
                        f"| {_cell(vuln.get('summary'))} | {_cell(fixed)} |"
                    )
            out.append("")

    if "tests" in sections:
        out += ["## Injection tests", ""]
        if not tests:
            out.append("No injection test ran in this conversation.")
        for record in tests:
            out.append(f"- {_cell((record.result or {}).get('summary') or record.message)}")
        out.append("")

    if "sources" in sections:
        out += ["## Sources cited", ""]
        if not cited:
            out.append("No Knowledge Base passage was cited in this conversation.")
        for citation in cited.values():
            heading = f" — {citation.get('heading')}" if citation.get("heading") else ""
            origin = str(citation.get("origin") or "")
            label = _cell(citation.get("source_title"))
            out.append(
                f"- [{label}]({origin}){heading}"
                if origin.startswith("https://")
                else f"- {label}{heading} ({_cell(origin)})"
            )
        out.append("")

    if "conversation" in sections:
        out += ["## Conversation", ""]
        for message in messages:
            if message.role == "user":
                out += [f"**Question:** {message.content.strip()}", ""]
            elif message.status == "complete":
                answer = message.content.strip()
                if len(answer) > MAX_ANSWER_CHARS:
                    answer = answer[:MAX_ANSWER_CHARS] + " …(shortened)"
                out += [answer, ""]

    markdown = "\n".join(out).strip() + "\n"
    if len(markdown) > MAX_REPORT_CHARS:
        markdown = markdown[:MAX_REPORT_CHARS] + "\n\n…(report shortened)\n"
    return title, markdown


class ReportService:
    def __init__(self, db: Session) -> None:
        self.db = db

    def create(self, user_id: int, conversation_id: str, sections: list[str]) -> Report:
        title, markdown = build_report(self.db, user_id, conversation_id, sections)
        report = Report(
            user_id=user_id, conversation_id=conversation_id, title=title, markdown=markdown
        )
        self.db.add(report)
        self.db.flush()
        return report

    def list(self, user_id: int) -> list[Report]:
        return list(
            self.db.scalars(
                select(Report).where(Report.user_id == user_id).order_by(Report.created_at.desc())
            )
        )

    def get(self, user_id: int, report_id: str) -> Report:
        report = self.db.get(Report, report_id)
        if report is None or report.user_id != user_id:
            raise NotFound("report not found")
        return report

    def delete(self, user_id: int, report_id: str) -> None:
        self.db.delete(self.get(user_id, report_id))
        self.db.flush()
